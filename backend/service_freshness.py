@dataclass
class ServiceFreshnessReport:
    """Per-round summary of the service-freshness preflight."""

    ports_requested: List[int] = field(default_factory=list)
    probes: List[PortProbe] = field(default_factory=list)
    decisions: Dict[int, str] = field(default_factory=dict)
    newest_source_mtime: Optional[float] = None
    # action: "noop" (no ports) | "healthy" (all healthy) |
    #        "restarted" | "blocked" (handled by the restart agent layer)
    action: str = "noop"
    detail: str = ""

    @property
    def needs_restart(self) -> List[int]:
        return sorted(
            port for port, dec in self.decisions.items()
            if dec == DECISION_RESTART
        )

    def to_dict(self) -> Dict[str, Any]:
        return {
            "ports_requested": list(self.ports_requested),
            "probes": [p.to_dict() for p in self.probes],
            "decisions": dict(self.decisions),
            "newest_source_mtime": self.newest_source_mtime,
            "action": self.action,
            "detail": self.detail,
        }


def assess_service_freshness(
    project_dir: Path,
    plan_data: dict,
) -> ServiceFreshnessReport:
    """Pure assessment: extract → probe → decide. No side effects.

    The caller (verification_agent preflight) turns ``needs_restart``
    into an actual restart via :mod:`service_restart_agent` and then
    re-probes to mark the report ``restarted``/``blocked``.
    """
    report = ServiceFreshnessReport()
    # ``project_dir`` is threaded through so the declared-services path
    # can validate each declaration's ``cwd``/``log_path`` containment
    # against the project it will actually run in.
    report.ports_requested = extract_service_ports(plan_data, project_dir)
    if not report.ports_requested:
        report.action = "noop"
        report.detail = "verification plan references no service ports"
        return report

    report.newest_source_mtime = newest_project_source_mtime(project_dir)
    for port in report.ports_requested:
        probe = probe_port(port)
        report.probes.append(probe)
        report.decisions[port] = classify_probe(
            probe, report.newest_source_mtime,
        )

    needed = report.needs_restart
    if needed:
        report.action = "restart_pending"
        report.detail = f"restart required for port(s) {needed}"
    else:
        report.action = "healthy"
        report.detail = "all referenced service ports are live and fresh"
    return report

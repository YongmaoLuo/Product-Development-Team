"""Tree snapshot — measure what a change did to a working tree.

Why this module exists
----------------------
The write guard is only allowed to *measure*, never to predict: it has
to be able to say "these N files changed" by looking at the tree, not
by reasoning about the command that was supposed to touch it.
``git status`` is not enough for that. It reports a path and a status,
but not the per-file ``(size, mtime_ns, sha256)`` triple the guard
needs to tell "rewritten with the same bytes" from "rewritten with
different bytes", and it cannot be replayed against a tree that has
already moved on.

This module is the reusable measurement primitive behind that guard::

    before = snapshot(root)
    ...                                  # something ran
    after = snapshot(root)
    report = diff(before, after)         # created / modified / deleted
    restore(root, before, report)        # put the tree back

What a snapshot covers
----------------------
* **Tracked files** — ``git ls-files -z`` (the index).
* **Untracked, non-ignored files** — ``git ls-files --others
  --exclude-standard -z``.
* **Not** ignored files, and **not** ``__pycache__`` directories:
  bytecode is build noise, never a side effect worth reporting.

Paths are always relative to ``root`` and always POSIX, so a snapshot
taken on one machine compares equal to the same tree on another.

What a snapshot does *not* cover
--------------------------------
The git *index* is not part of the snapshot, only the working tree it
points at. A file that was staged for deletion is therefore invisible
to ``snapshot`` even though the index still remembers it — the file is
gone from the tree, and that is what the tree says.

The hashing rule
----------------
A file whose ``(size, mtime_ns)`` did not change is **not** hashed
again: the hash computed last time is still the truth, and re-hashing
every file of a tree on every poll is what makes a measuring guard
expensive enough that people switch it off. The rule is enforced by a
memo keyed by ``(root, path)`` and validated by ``(size, mtime_ns)``,
so a memoised hash can only ever be returned for a file whose metadata
says it has not been touched.

The cost of the rule is that a content change which keeps both the size
and the mtime identical is invisible. That is a deliberate trade: the
alternative is hashing the whole tree on every measurement, and a
guard nobody can afford to run measures nothing at all.

Restoring
---------
``restore`` puts the tree back the way the snapshot found it:

* a **created** file is removed;
* a **modified** file is checked out from the index;
* a **deleted** tracked file is resurrected with ``git checkout --``.

Restoring therefore restores *the index's* version of a file, which is
the committed version when the tree was clean when the snapshot was
taken. A file that was already dirty at snapshot time cannot be put
back byte for byte — the snapshot records the hash of what was on
disk, not the bytes themselves — so ``restore`` reports the paths it
could put back and logs the ones it could not.
"""

from __future__ import annotations

import hashlib
import logging
import os
import stat
import subprocess
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath
from typing import Dict, List, Optional, Tuple

logger = logging.getLogger(__name__)

#: Hard ceiling on a single git invocation. A hung git must not hang
#: the guard whose whole job is to *measure* the tree.
GIT_TIMEOUT_SEC = 30

#: Size of one hashing chunk. Files are read in chunks so a large
#: artefact does not have to fit in memory all at once.
_HASH_CHUNK_SIZE = 1 << 20

#: Path components that are never reported as a side effect. Compiled
#: bytecode is regenerated by the interpreter on its own; reporting it
#: would make every tree look mutated after the first import.
_EXCLUDED_COMPONENTS = frozenset({"__pycache__"})

#: Upper bound on the hash memo. The memo exists to avoid re-hashing an
#: unchanged tree; it is a cache, not a ledger, so dropping it wholesale
#: is always safe (the next snapshot re-hashes what it needs).
_MEMO_MAX_ENTRIES = 50_000


class NotARepositoryError(Exception):
    """The snapshot root is not inside a git working tree.

    Deliberately **not** a ``RuntimeError``: the caller has to tell
    "this directory is not a repository, so there is nothing to
    measure" apart from "the measuring code itself broke". A guard that
    cannot measure must say so, not silently treat the tree as empty.
    """


@dataclass(frozen=True)
class Entry:
    """What was measured about one file.

    ``sha256`` is ``None`` for a path that has no content to hash (a
    symlink, a directory git tracks, a file that could not be read).
    """

    size: int
    mtime_ns: int
    sha256: Optional[str]


@dataclass(frozen=True)
class Snapshot:
    """The measured state of one working tree at one point in time."""

    root: str
    entries: Dict[str, Entry]


@dataclass(frozen=True)
class MutationReport:
    """What changed between two snapshots.

    Every list holds paths relative to the snapshot root, in POSIX form,
    sorted.
    """

    created: List[str] = field(default_factory=list)
    modified: List[str] = field(default_factory=list)
    deleted: List[str] = field(default_factory=list)


#: ``(root, path) -> Entry`` memo of the files already hashed. See the
#: module docstring for the rule it encodes and the trade it buys.
_MEMO: Dict[Tuple[str, str], Entry] = {}


def _run_git(root: Path, args: List[str]) -> subprocess.CompletedProcess:
    """Run ``git`` inside ``root`` and return the completed process.

    The exit code is *not* checked here: every caller decides what a
    non-zero exit means for it.
    """
    return subprocess.run(
        ["git", "-C", str(root), *args],
        capture_output=True,
        check=False,
        timeout=GIT_TIMEOUT_SEC,
    )


def _assert_work_tree(root: Path) -> None:
    """Raise :class:`NotARepositoryError` unless ``root`` is in a work tree."""
    proc = _run_git(root, ["rev-parse", "--is-inside-work-tree"])
    if proc.returncode != 0:
        stderr = (proc.stderr or b"").decode("utf-8", errors="replace").strip()
        raise NotARepositoryError(
            f"{root} is not a git working tree" + (f": {stderr}" if stderr else "")
        )
    answer = (proc.stdout or b"").decode("utf-8", errors="replace").strip()
    if answer != "true":
        raise NotARepositoryError(f"{root} is not a git working tree")


def _list_paths(root: Path, args: List[str]) -> List[str]:
    """Run a NUL-separated ``git ls-files`` and return its paths.

    The paths git prints are relative to the directory it was run in, so
    they are relative to ``root`` — which is exactly the form the
    snapshot contract asks for.
    """
    proc = _run_git(root, args)
    if proc.returncode != 0:
        stderr = (proc.stderr or b"").decode("utf-8", errors="replace").strip()
        raise NotARepositoryError(
            f"git {' '.join(args)} failed in {root} "
            f"(exit {proc.returncode}): {stderr}"
        )
    paths: List[str] = []
    for chunk in (proc.stdout or b"").split(b"\0"):
        if not chunk:
            continue
        text = chunk.decode("utf-8", errors="surrogateescape")
        paths.append(PurePosixPath(text).as_posix())
    return paths


def _sha256_file(path: Path) -> Optional[str]:
    """Return the SHA-256 of ``path``, or ``None`` when it cannot be read."""
    digest = hashlib.sha256()
    try:
        with open(path, "rb") as handle:
            for chunk in iter(lambda: handle.read(_HASH_CHUNK_SIZE), b""):
                digest.update(chunk)
    except OSError as exc:
        logger.warning("could not hash %s: %s", path, exc)
        return None
    return digest.hexdigest()


def _memo_key(root: Path, rel: str) -> Tuple[str, str]:
    """Key the hash memo by the resolved root and the relative path."""
    return (str(Path(root).resolve()), rel)


def _is_excluded(rel: str) -> bool:
    """True for a path that is never reported as a side effect."""
    return any(part in _EXCLUDED_COMPONENTS for part in PurePosixPath(rel).parts)


def _same_root(root: Path, other: str) -> bool:
    """True when two roots name the same directory."""
    try:
        return Path(root).resolve() == Path(other).resolve()
    except OSError:
        return False


def _reusable_entry(
    root: Path,
    rel: str,
    previous: Optional[Snapshot],
    info: os.stat_result,
) -> Optional[Entry]:
    """Return the entry measured last time, when the file has not changed.

    Two sources are consulted, in order: the snapshot the caller passed
    in, and the module's own memo. Both are validated against the
    file's current ``(size, mtime_ns)``, so neither can return a hash
    for a file that has been touched since.
    """
    candidates: List[Optional[Entry]] = []
    if previous is not None and _same_root(root, previous.root):
        candidates.append(previous.entries.get(rel))
    candidates.append(_MEMO.get(_memo_key(root, rel)))

    for candidate in candidates:
        if candidate is None:
            continue
        if candidate.size == info.st_size and candidate.mtime_ns == info.st_mtime_ns:
            return candidate
    return None


def _measure(root: Path, rel: str, previous: Optional[Snapshot]) -> Optional[Entry]:
    """Measure one file, or return ``None`` when it is not there.

    ``None`` means the file disappeared from the working tree. That is
    not an error: the file is still listed by the index, but the tree
    no longer has it, and the diff reports it as deleted by its
    absence.
    """
    path = root / rel
    try:
        info = os.lstat(path)
    except OSError:
        return None

    if not stat.S_ISREG(info.st_mode):
        # A symlink, a directory git tracks, a fifo: there is no file
        # content to hash, so only the metadata is recorded.
        return Entry(size=info.st_size, mtime_ns=info.st_mtime_ns, sha256=None)

    reusable = _reusable_entry(root, rel, previous, info)
    if reusable is not None:
        return reusable

    entry = Entry(
        size=info.st_size,
        mtime_ns=info.st_mtime_ns,
        sha256=_sha256_file(path),
    )
    if len(_MEMO) >= _MEMO_MAX_ENTRIES:
        _MEMO.clear()
    _MEMO[_memo_key(root, rel)] = entry
    return entry


def snapshot(root: Path, previous: Optional[Snapshot] = None) -> Snapshot:
    """Measure the working tree at ``root``.

    Args:
        root: The directory to measure. It has to sit inside a git
            working tree.
        previous: An earlier snapshot of the same tree. When a file's
            ``(size, mtime_ns)`` has not changed since that snapshot,
            its hash is taken from there instead of being computed
            again.

    Returns:
        A :class:`Snapshot` whose entries are keyed by relative POSIX
        path and sorted by path.

    Raises:
        NotARepositoryError: When ``root`` is not inside a git working
            tree.
    """
    root = Path(root)
    _assert_work_tree(root)

    tracked = _list_paths(root, ["ls-files", "-z"])
    untracked = _list_paths(root, ["ls-files", "--others", "--exclude-standard", "-z"])

    entries: Dict[str, Entry] = {}
    for rel in sorted(set(tracked) | set(untracked)):
        if _is_excluded(rel):
            continue
        entry = _measure(root, rel, previous)
        if entry is None:
            continue
        entries[rel] = entry
    return Snapshot(root=str(root), entries=entries)


def _is_modified(before: Entry, after: Entry) -> bool:
    """True when the two measurements of one path differ.

    The content decides when both hashes are known: a file that was
    rewritten with the same bytes is not a changed file. When a hash is
    missing (a symlink, a file that could not be read) the metadata
    decides instead.
    """
    if before.sha256 is not None and after.sha256 is not None:
        return before.sha256 != after.sha256
    return before.size != after.size or before.mtime_ns != after.mtime_ns


def diff(before: Snapshot, after: Snapshot) -> MutationReport:
    """Compare two snapshots of the same tree.

    Args:
        before: The earlier snapshot.
        after: The later snapshot.

    Returns:
        A :class:`MutationReport` whose three lists hold relative POSIX
        paths, sorted.
    """
    before_entries = before.entries
    after_entries = after.entries

    created = sorted(path for path in after_entries if path not in before_entries)
    deleted = sorted(path for path in before_entries if path not in after_entries)
    modified = sorted(
        path
        for path in before_entries
        if path in after_entries
        and _is_modified(before_entries[path], after_entries[path])
    )
    return MutationReport(created=created, modified=modified, deleted=deleted)


def _restore_tracked(root: Path, rel: str) -> bool:
    """Put one tracked path back from the index.

    ``git checkout -- <path>`` restores what the index holds. When the
    path is not in the index any more (it was staged away with
    ``git rm``) the committed version is used instead.
    """
    proc = _run_git(root, ["checkout", "--", rel])
    if proc.returncode == 0:
        return True
    fallback = _run_git(root, ["checkout", "HEAD", "--", rel])
    if fallback.returncode == 0:
        return True
    stderr = (fallback.stderr or proc.stderr or b"").decode(
        "utf-8", errors="replace"
    ).strip()
    logger.warning("could not restore %s: %s", rel, stderr)
    return False


def _remove_created(root: Path, rel: str) -> bool:
    """Remove a path that did not exist in the snapshot."""
    path = root / rel
    try:
        if path.is_symlink() or path.is_file():
            path.unlink()
            return True
    except OSError as exc:
        logger.warning("could not remove %s: %s", rel, exc)
        return False
    if path.exists():
        logger.warning("could not remove %s: not a regular file", rel)
        return False
    # Already gone: the state the snapshot describes is the state the
    # tree is in.
    return True


def _matches_snapshot(root: Path, before: Snapshot, rel: str) -> bool:
    """True when the file on disk now hashes to what the snapshot recorded."""
    expected = before.entries.get(rel)
    if expected is None or expected.sha256 is None:
        return True
    actual = _sha256_file(root / rel)
    if actual != expected.sha256:
        logger.warning(
            "restored %s does not match the snapshot: %s != %s",
            rel,
            actual,
            expected.sha256,
        )
        return False
    return True


def restore(root: Path, before: Snapshot, report: MutationReport) -> List[str]:
    """Put the working tree back the way ``before`` found it.

    Args:
        root: The tree to restore.
        before: The snapshot the tree should be brought back to.
        report: The mutations to undo, as produced by :func:`diff`.

    Returns:
        The relative POSIX paths that now match the snapshot, sorted.
        A path that could not be put back (an untracked file whose
        content the snapshot does not hold, for instance) is not in the
        list and is logged.
    """
    root = Path(root)
    restored: List[str] = []

    for rel in report.deleted:
        if _restore_tracked(root, rel) and _matches_snapshot(root, before, rel):
            restored.append(rel)

    for rel in report.modified:
        if _restore_tracked(root, rel) and _matches_snapshot(root, before, rel):
            restored.append(rel)

    for rel in report.created:
        if _remove_created(root, rel):
            restored.append(rel)

    return sorted(set(restored))
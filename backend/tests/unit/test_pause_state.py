"""The pause checkpoint survives the process that wrote it.

What this pins
--------------
``stop`` used to be pure in-memory state: a plan was stopped, the
executor dropped the task handles, and a restart of the backend came
back to a plan that looked exactly like a plan that had never run.
There was nothing on disk to say "this was interrupted mid-task 3,
with a resumable session id attached".

``backend/pause_state.py`` is the file layer that closes that gap, and
these five tests pin the *file* contract only -- no executor, no
scheduler, no routes:

* **round trip** -- what the caller handed over is what a fresh read
  gives back, including the per-entry ``interrupted_tasks`` shape;
* **missing** -- a plan that never stopped reads as ``None``;
* **corrupt** -- a checkpoint torn by a crash reads as ``None``, never
  as an exception, because "resume from scratch" must always be a
  reachable answer;
* **consume** -- read-then-delete, so the second resume does not
  re-consume the same interruption forever;
* **summary** -- the projection the UI needs (kind + how many tasks
  were in flight) without dragging the whole checkpoint around.

The three extra tests pin the boundary conditions the module promises:
``plan_dir`` is created on demand, ``clear`` is idempotent, and both
task lists are normalised to their fixed key sets so a caller cannot
smuggle extra fields into the on-disk contract.

Note that ``paused_at`` is generated by the writer, not by the caller
(there is no parameter for it), so the round-trip test asserts equality
against the dict the *write* returned rather than against a
hand-written timestamp -- which is the only assertion here that would
still hold in 2030.
"""

import json
from pathlib import Path

from pause_state import (
    PAUSE_CHECKPOINT_FILENAME,
    checkpoint_path,
    checkpoint_summary,
    clear_pause_checkpoint,
    consume_pause_checkpoint,
    read_pause_checkpoint,
    write_pause_checkpoint,
)

#: One interrupted task carrying every field of the fixed entry shape,
#: plus one unfinished task in its two-field shape.
INTERRUPTED = [
    {
        "task_id": "3",
        "status": "in_progress",
        "phase": "execution",
        "session_id": "s-1",
        "paused_at": "2026-10-20T12:00:00",
        "strategy": "session_resume",
        "reason": "session_id_available",
    }
]
UNFINISHED = [{"task_id": "3", "status": "in_progress"}]


def _write(plan_dir, **overrides):
    """Write a checkpoint, letting a test override one keyword."""
    kwargs = {
        "kind": "execution",
        "project_dir": "/w/app",
        "reason": "user_requested",
        "interrupted_tasks": INTERRUPTED,
        "unfinished_tasks": UNFINISHED,
    }
    kwargs.update(overrides)
    return write_pause_checkpoint(plan_dir, **kwargs)


def test_write_read_roundtrip(tmp_path):
    """Everything handed to the writer comes back from a fresh read."""
    written = _write(tmp_path)

    assert written["kind"] == "execution"
    read = read_pause_checkpoint(tmp_path)
    assert read == written
    assert read["kind"] == "execution"
    assert read["project_dir"] == "/w/app"
    assert read["reason"] == "user_requested"
    assert read["version"] == 1
    assert read["interrupted_tasks"] == INTERRUPTED
    assert read["unfinished_tasks"] == UNFINISHED
    # ``verification_round`` is optional and defaults to None, never a KeyError.
    assert read["verification_round"] is None
    # The writer stamps the timestamp; it must be a non-empty string.
    assert isinstance(read["paused_at"], str) and read["paused_at"]


def test_read_missing_returns_none(tmp_path):
    """A plan that never stopped has no checkpoint -- not an error."""
    empty = tmp_path / "never-ran"
    empty.mkdir()

    assert read_pause_checkpoint(empty) is None
    assert consume_pause_checkpoint(empty) is None
    assert checkpoint_summary(empty) is None


def test_read_corrupt_returns_none(tmp_path):
    """A checkpoint torn mid-write reads as absent, never raises."""
    checkpoint_path(tmp_path).write_text("{bad", encoding="utf-8")

    assert read_pause_checkpoint(tmp_path) is None
    assert consume_pause_checkpoint(tmp_path) is None
    assert checkpoint_summary(tmp_path) is None
    # The corrupt file is still there to inspect -- consume must not have
    # deleted something it could not parse.
    assert checkpoint_path(tmp_path).exists()


def test_consume_removes_file(tmp_path):
    """Consume is read-then-delete: the second resume finds nothing."""
    _write(tmp_path)
    assert checkpoint_path(tmp_path).exists()

    first = consume_pause_checkpoint(tmp_path)
    assert first["kind"] == "execution"
    assert first["interrupted_tasks"] == INTERRUPTED
    assert not checkpoint_path(tmp_path).exists()

    # Second time round there is nothing left to resume from.
    assert consume_pause_checkpoint(tmp_path) is None


def test_consume_survives_delete_failure(tmp_path, monkeypatch):
    """A delete that fails is silent: the caller still gets the checkpoint.

    The checkpoint has already been read at this point, so raising would
    turn a resumable stop into a failed resume over a file the process
    can no longer remove.
    """
    _write(tmp_path)

    def _boom(*args, **kwargs):
        raise OSError("read-only filesystem")

    monkeypatch.setattr(Path, "unlink", _boom)

    assert consume_pause_checkpoint(tmp_path)["kind"] == "execution"
    clear_pause_checkpoint(tmp_path)  # no raise


def test_summary_projects_counts(tmp_path):
    """The projection carries kind and the in-flight task count."""
    _write(tmp_path, verification_round=2)

    summary = checkpoint_summary(tmp_path)
    assert summary["kind"] == "execution"
    assert summary["interrupted_task_count"] == 1
    assert summary["project_dir"] == "/w/app"
    assert summary["verification_round"] == 2
    assert set(summary) == {
        "paused_at",
        "kind",
        "project_dir",
        "interrupted_task_count",
        "verification_round",
    }
    # The projection is not the checkpoint: it must not leak the task
    # bodies to a caller that only asked for counts.
    assert "interrupted_tasks" not in summary


def test_write_creates_missing_plan_dir(tmp_path):
    """A plan directory that does not exist yet is created on demand."""
    plan_dir = tmp_path / "not" / "created" / "yet"

    _write(plan_dir)

    assert checkpoint_path(plan_dir) == plan_dir / PAUSE_CHECKPOINT_FILENAME
    assert checkpoint_path(plan_dir).exists()
    assert read_pause_checkpoint(plan_dir)["kind"] == "execution"


def test_clear_is_idempotent(tmp_path):
    """Clearing twice is a no-op, and clearing nothing does not raise."""
    _write(tmp_path)

    clear_pause_checkpoint(tmp_path)
    assert read_pause_checkpoint(tmp_path) is None

    clear_pause_checkpoint(tmp_path)  # no raise
    clear_pause_checkpoint(tmp_path / "never-existed")


def test_entries_normalised_to_fixed_keys(tmp_path):
    """Extra keys cannot enter the on-disk contract; missing ones are None."""
    _write(
        tmp_path,
        interrupted_tasks=[
            {"task_id": 7, "status": "in_progress", "session_id": "s-2", "junk": "x"}
        ],
        unfinished_tasks=[{"task_id": 7, "sneaky": 1}],
    )

    on_disk = json.loads(checkpoint_path(tmp_path).read_text(encoding="utf-8"))
    interrupted = on_disk["interrupted_tasks"][0]
    assert set(interrupted) == {
        "task_id",
        "status",
        "phase",
        "session_id",
        "paused_at",
        "strategy",
        "reason",
    }
    assert "junk" not in interrupted
    # An entry that omits paused_at inherits the checkpoint's timestamp
    # rather than losing it.
    assert interrupted["paused_at"] == on_disk["paused_at"]
    assert set(on_disk["unfinished_tasks"][0]) == {"task_id", "status"}
    assert on_disk["unfinished_tasks"][0]["status"] is None
    assert set(on_disk) == {
        "version",
        "kind",
        "project_dir",
        "paused_at",
        "reason",
        "interrupted_tasks",
        "unfinished_tasks",
        "verification_round",
    }
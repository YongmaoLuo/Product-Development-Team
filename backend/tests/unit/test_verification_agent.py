def _build_plan_payload(*, methods, priorities):
    vps = []
    for idx, (method, priority) in enumerate(zip(methods, priorities), start=1):
        vp = {
            "id": f"VP-{idx:03d}",
            "title": f"Verification point {idx}",
            "related_prd_criteria": "Relevant PRD criterion",
            "verification_method": method,
            "priority": priority,
            "expected_result": "Expected outcome",
        }
        # api_test VPs must carry a runnable request/assertions envelope
        # so the deterministic runner can grade them (the 2026-09
        # ``repair-r4-01`` gate rejects plans whose api_test VPs lack
        # either half). The earlier fixture omitted both, and the gate
        # then tripped before the assertions below could run.
        if method == "api_test":
            vp["request"] = {
                "method": "GET",
                "url": "{{svc.example.url}}/api/items",
            }
            vp["assertions"] = [{"status": 200}]
        vps.append(vp)
    return {"verification_points": vps}


async def _stub_code_review_async(vp, vp_id=None):
    """Async stub that returns a PASSED result dict for one VP.

    Bound to the agent instance via
    ``type(executor).__name__ == 'function'`` so the per-VP dispatcher
    in :meth:`_run_single_vp_async` detects the patch (the canonical
    class-defined method has ``type.__name__ == 'method'``) and uses
    this stub instead of the canonical sub-agent path. The dispatcher
    then awaits ``_execute_automated_test(vp)`` — we provide a sync
    shim that returns the same dict directly so no extra ``await``
    machinery is needed.
    """
    return {
        "id": vp.get("id", "unknown"),
        "status": "PASSED",
        "actual_result": "stub ok",
        "reasons": ["stub"],
        "evidence": "stub",
    }


def _stub_code_review_sync(vp, vp_id=None):
    """Sync shim paired with ``_stub_code_review_async``.

    The dispatcher awaits ``_execute_automated_test(vp)`` after
    detecting the async-version patch, so this shim must return the
    same shape directly.
    """
    return _stub_code_review_async.__wrapped__(vp) if hasattr(
        _stub_code_review_async, "__wrapped__"
    ) else {
        "id": vp.get("id", "unknown"),
        "status": "PASSED",
        "actual_result": "stub ok",
        "reasons": ["stub"],
        "evidence": "stub",
    }


def _install_code_review_stub(agent):
    """Patch the per-method executor on the agent instance.

    The dispatcher probes ``_execute_<method>_async`` first, then
    ``_execute_<method>``, and requires ``type(executor).__name__ ==
    'function'`` (a class-defined bound method is ``'method'``). The
    async spelling is the one that is awaited, so that is what gets
    patched here.
    """
    agent._execute_code_review_async = _stub_code_review_async



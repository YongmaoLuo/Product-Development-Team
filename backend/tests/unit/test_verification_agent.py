def test_execute_verification_plan(verification_agent, mock_coding_tool,
                                    temp_plan_dir):
    # Phase 1 keeps automated_test / code_review / ui_validation /
    # api_test VPs and drops manual_check; pick automated_test so the
    # plan survives the filter. Monkey-patch the per-method executor
    # on the agent instance — the dispatcher detects the patch via
    # ``type(executor).__name__ == 'function'`` and uses the stub
    # instead of the canonical sub-agent path, which keeps the test
    # hermetic and independent of any LLM backend.
    mock_coding_tool.query_json.return_value = _build_plan_payload(
        methods=["code_review", "code_review"],
        priorities=["high", "medium"],
    )
    plan = verification_agent.generate_verification_plan()
    assert len(plan["verification_points"]) == 2

    _install_code_review_stub(verification_agent)

    results = verification_agent.execute_verification_plan(plan)

    assert isinstance(results, dict)
    assert "execution_results" in results
    assert "verification_points" in results
    assert isinstance(results["execution_results"], list)
    assert len(results["execution_results"]) == 2

    ids = [r.get("id") for r in results["execution_results"]]
    assert "VP-001" in ids
    assert "VP-002" in ids

    for r in results["execution_results"]:
        assert r.get("status") == "PASSED"
        assert "actual_result" in r

    # The agent persists the execution results so the report phase
    # can pick them up from SQLite (``plan_verification.execution_results``)
    # even when the caller does not pass them in. The legacy on-disk
    # cache at ``plans/{id}/verification_execution_results.json`` is
    # no longer written — see task #3.5.
    assert verification_agent.verif_repo is not None, (
        "expected verification_agent.verif_repo to be wired by the fixture"
    )
    stored = verification_agent.verif_repo.current(
        verification_agent.plan_dir.name
    )
    assert stored is not None
    assert stored.get("execution_results") == results


def test_generate_verification_report(verification_agent, mock_coding_tool,
                                      temp_plan_dir):
    # Drive execute_verification_plan with monkey-patched
    # ``_execute_automated_test`` so we don't need a real LLM /
    # sub-agent. The report generator still calls
    # ``coding_tool.query_json`` for the LLM-driven judgment.
    mock_coding_tool.query_json.return_value = _build_plan_payload(
        methods=["code_review", "code_review"],
        priorities=["high", "medium"],
    )
    plan = verification_agent.generate_verification_plan()
    _install_code_review_stub(verification_agent)
    execution_results = verification_agent.execute_verification_plan(plan)

    # The LLM-emitted report payload from Phase 3. Two VPs, one
    # PASSED, one FAILED, plus a requirement deviation entry. The
    # generator re-derives ``overall_status`` from the per-VP
    # statuses (see generate_verification_report in
    # backend/verification_agent.py), so what we assert against is
    # the final, post-rewrite state, not the raw LLM payload.
    mock_coding_tool.query_json.return_value = {
        "overall_status": "FAILED",
        "summary": "mixed verdicts",
        "verification_results": [
            {
                "id": "VP-001",
                "status": "PASSED",
                "actual_result": "ok",
                "reasons": [],
                "evidence": "",
            },
            {
                "id": "VP-002",
                "status": "FAILED",
                "actual_result": "missing feature X",
                "reasons": ["missing feature X"],
                "evidence": "X not found in code",
            },
        ],
        "requirement_deviations": [
            {
                "vp_id": "VP-002",
                "deviation_type": "missing",
                "severity": "high",
                "description": "missing feature X",
            },
        ],
    }

    report = verification_agent.generate_verification_report(execution_results)

    assert isinstance(report, dict)
    assert "overall_status" in report
    # FAILED is allowed because the LLM-emitted verdict list contains
    # at least one FAILED VP, and the post-rewrite logic preserves it.
    assert report["overall_status"] in {"PASSED", "FAILED", "LOOP_STOPPED"}

    # requirement_deviations must be a list (may be empty, but never
    # missing or a non-list).
    assert "requirement_deviations" in report
    assert isinstance(report["requirement_deviations"], list)
    assert report["requirement_deviations"]  # populated in this fixture

    # The per-VP results must be present and the count must match the
    # number of VPs we executed.
    assert "verification_results" in report
    assert isinstance(report["verification_results"], list)
    assert len(report["verification_results"]) == 2

    statuses = [vr.get("status") for vr in report["verification_results"]]
    passed = sum(1 for s in statuses if s == "PASSED")
    failed = sum(1 for s in statuses if s == "FAILED")
    skipped = sum(1 for s in statuses if s == "SKIPPED")
    assert passed + failed + skipped == len(report["verification_results"])

    # Report is persisted so downstream consumers can pick it up from
    # disk without re-running Phase 3.
    report_file = temp_plan_dir / "verification_report.json"
    assert report_file.exists()
    with open(report_file) as f:
        on_disk = json.load(f)
    assert on_disk == report


def test_plan_schema(verification_agent, mock_coding_tool):
    mock_coding_tool.query_json.return_value = _build_plan_payload(
        methods=["code_review", "ui_validation", "api_test",
                 "api_test"],
        priorities=["high", "medium", "low", "high"],
    )

    plan = verification_agent.generate_verification_plan()

    assert isinstance(plan["verification_points"], list)
    assert plan["verification_points"], "plan must contain at least one VP"

    for vp in plan["verification_points"]:
        for field in REQUIRED_VP_FIELDS:
            assert field in vp, f"VP {vp.get('id', '?')} missing field: {field}"

        assert isinstance(vp["id"], str)
        assert isinstance(vp["title"], str)
        assert isinstance(vp["related_prd_criteria"], str)
        assert isinstance(vp["verification_method"], str)
        assert isinstance(vp["priority"], str)
        assert isinstance(vp["expected_result"], str)

        assert vp["priority"] in VALID_PRIORITIES, (
            f"Invalid priority {vp['priority']!r} in VP {vp['id']}"
        )
        assert vp["verification_method"] in VALID_METHODS, (
            f"Invalid method {vp['verification_method']!r} in VP {vp['id']}"
        )

    # All VPs (including manual_check) survive Phase 1. The new
    # behavior keeps manual_check VPs in the plan and flags them
    # for human review, instead of dropping them. Non-manual_check
    # methods are still in KEPT_METHODS.
    for vp in plan["verification_points"]:
        assert vp["verification_method"] in VALID_METHODS




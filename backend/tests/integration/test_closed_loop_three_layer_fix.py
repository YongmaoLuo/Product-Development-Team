"""End-to-end test pinning the three-layer RP-* persistence + closed-loop
fix shipped 2026-09-12.

Layer 1: ``_get_pending_repair_tasks`` accepts post-v9 ``R{n}-{i}`` ids
         (not just legacy ``RP-<n>``).
Layer 2: ``_run_auto_verification_loop`` overrides ``status="passed"`` to
         ``"failed"`` when pending DB tasks remain, so the
         ``verification_passed → verification_repairing`` legal-edge path
         can be reached for the executor queue.
Layer 3: ``_load_repair_tasks_for_progress`` aggregates RP-* across all
         three layers (in-memory + disk v2 + state.db ``task_group LIKE
         'repair%'``).

These three fixes unblock pending repair work: RP-* tasks generated by
an earlier round are still outstanding and must be dispatched, whether
or not the current round produces new ones.
"""
from __future__ import annotations

import json

import pytest
from tests.app_source import app_source


def test_layer1_pending_filter_accepts_post_v9_ids():
    """Layer 1: ``_get_pending_repair_tasks`` returns R{n}-* ids (not
    only legacy RP-*)."""
    from state_machine.db.connection import open as open_db
    from state_machine.db.schema import migrate
    from state_machine.repositories.plan_task_repository import (
        PlanTaskRepository,
    )
    import tempfile

    with tempfile.TemporaryDirectory() as tmpdir:
        db_path = Path(tmpdir) / "state.db"
        conn = open_db(db_path)
        try:
            migrate(conn)
            repo = PlanTaskRepository(conn)
            # ``status`` is a runtime field, set via update_task, not add_task.
            repo.add_task("plan", {
                "id": "R6-2", "title": "fix VP-027",
                "task_group": "repair-round-6",
            })
            repo.update_task("plan", "R6-2", {"status": "pending"})
            repo.add_task("plan", {
                "id": "RP-1", "title": "fix VP-006",
                "task_group": "repair",
            })
            repo.update_task("plan", "RP-1", {"status": "pending"})
        finally:
            conn.close()

        # Patch server._state_db_path
        import server
        server._state_db_path = lambda request=None: db_path

        pending = server._get_pending_repair_tasks("plan")
        ids = {t["id"] for t in pending}
        assert ids == {"R6-2", "RP-1"}, f"got {ids}"


